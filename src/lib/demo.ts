import type { PortalData, Training } from "./types";
const event = (
  id: string,
  day: string,
  time: string,
  status: "planned" | "attended_auto" | "excused",
  title = "Technik & Spielintelligenz",
  player = "max",
): Training => {
  const start = localToUtc(day, time),
    end = new Date(new Date(start).getTime() + 90 * 60000).toISOString();
  return {
    id,
    title,
    starts_at: start,
    ends_at: end,
    location_id: "sportpark",
    location_name: "Sportpark Gelsenkirchen",
    address: "Auf der Reihe 59, 45884 Gelsenkirchen",
    trainer_id: "muhsin",
    trainer_name: "Muhsin Ayhan",
    event_type: "Gruppentraining",
    status: "scheduled",
    auto_attendance_at: calculateAutoAttendanceAt(end),
    participants: [
      {
        id: `p-${id}`,
        player_id: player,
        period_id: player === "max" ? "period-max" : "period-lena",
        status,
      },
    ],
  };
};
